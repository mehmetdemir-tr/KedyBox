void test_gradient(void) {
    for (int y = 0; y < (int)fb.height; y++)
        for (int x = 0; x < (int)fb.width; x++) {
            uint8_t r = (uint8_t)(255 * x / fb.width);
            uint8_t g = (uint8_t)(255 * y / fb.height);
            put_pixel(x, y, rgb(r, g, 100));
        }
    draw_text(20, 20, "Gradient test", rgb(255, 255, 255), 2);
    fb_flip();
    usleep(900000);
}

int main(int argc, char **argv) {
    const char *fbdev = argc > 1 ? argv[1] : NULL;

    printf("PatiOS pineapple - FB test\n");

    if (fb_init(fbdev) < 0)
        return 1;

    test_clear();
    test_rects();
    test_outlines();
    test_lines();
    test_circles();
    test_text();
    test_gradient();

    fill_screen(rgb(0, 0, 0));
    fb_flip();

    fb_destroy();
    printf("All tests done.\n");
    return 0;
}
