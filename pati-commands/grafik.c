typedef struct {
    int   fd;
    uint8_t *buf;
    uint8_t *backbuf;
    uint32_t width;
    uint32_t height;
    uint32_t pitch;
    uint32_t bpp;
    uint32_t size;
} FB;

static FB fb;

int fb_init(const char *dev) {
    struct fb_var_screeninfo vinfo;
    struct fb_fix_screeninfo finfo;
    char fbdev[32];
    int try;

    for (try = 0; try < 8; try++) {
        if (dev && try == 0)
            snprintf(fbdev, sizeof(fbdev), "%s", dev);
        else
            snprintf(fbdev, sizeof(fbdev), "/dev/fb%d", try);

        fb.fd = open(fbdev, O_RDWR);
        if (fb.fd >= 0) break;

        if (errno == EACCES) {
            chmod(fbdev, 0666);
            fb.fd = open(fbdev, O_RDWR);
            if (fb.fd >= 0) break;
        }
    }

    if (fb.fd < 0) {
        fprintf(stderr, "No framebuffer found. Try: chmod 666 /dev/fb0\n");
        return -1;
    }

    if (ioctl(fb.fd, FBIOGET_FSCREENINFO, &finfo) < 0) { perror("ioctl"); return -1; }
    if (ioctl(fb.fd, FBIOGET_VSCREENINFO, &vinfo) < 0) { perror("ioctl"); return -1; }

    fb.width  = vinfo.xres;
    fb.height = vinfo.yres;
    fb.bpp    = vinfo.bits_per_pixel;
    fb.pitch  = finfo.line_length;
    fb.size   = fb.pitch * fb.height;

    printf("FB: %ux%u %ubpp pitch=%u size=%u\n",
           fb.width, fb.height, fb.bpp, fb.pitch, fb.size);

    fb.buf = mmap(NULL, fb.size, PROT_READ | PROT_WRITE, MAP_SHARED, fb.fd, 0);
    if (fb.buf == MAP_FAILED) { perror("mmap"); return -1; }

    fb.backbuf = malloc(fb.size);
    if (!fb.backbuf) { perror("malloc"); return -1; }

    return 0;
}

void fb_destroy(void) {
    if (fb.backbuf) free(fb.backbuf);
    if (fb.buf && fb.buf != MAP_FAILED) munmap(fb.buf, fb.size);
    if (fb.fd >= 0) close(fb.fd);
}

void fb_flip(void) {
    memcpy(fb.buf, fb.backbuf, fb.size);
}

static inline uint32_t rgb(uint8_t r, uint8_t g, uint8_t b) {
    return (0xFF << 24) | (r << 16) | (g << 8) | b;
}

static inline void put_pixel(int x, int y, uint32_t color) {
    if ((unsigned)x >= fb.width || (unsigned)y >= fb.height) return;
    uint32_t *p = (uint32_t *)(fb.backbuf + y * fb.pitch + x * (fb.bpp / 8));
    *p = color;
}

void fill_screen(uint32_t color) {
    uint32_t *p = (uint32_t *)fb.backbuf;
    uint32_t pixels = fb.size / (fb.bpp / 8);
    for (uint32_t i = 0; i < pixels; i++) p[i] = color;
}

void fill_rect(int x, int y, int w, int h, uint32_t color) {
    for (int row = y; row < y + h; row++)
        for (int col = x; col < x + w; col++)
            put_pixel(col, row, color);
}

void draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int col = x; col < x + w; col++) {
        put_pixel(col, y, color);
        put_pixel(col, y + h - 1, color);
    }
    for (int row = y; row < y + h; row++) {
        put_pixel(x, row, color);
        put_pixel(x + w - 1, row, color);
    }
}

void draw_line(int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    while (1) {
        put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void draw_circle(int cx, int cy, int r, uint32_t color) {
    int x = r, y = 0, err = 0;
    while (x >= y) {
        put_pixel(cx + x, cy + y, color); put_pixel(cx - x, cy + y, color);
        put_pixel(cx + x, cy - y, color); put_pixel(cx - x, cy - y, color);
        put_pixel(cx + y, cy + x, color); put_pixel(cx - y, cy + x, color);
        put_pixel(cx + y, cy - x, color); put_pixel(cx - y, cy - x, color);
        y++;
        if (err <= 0) { err += 2 * y + 1; }
        else          { x--; err += 2 * (y - x) + 1; }
    }
}

void fill_circle(int cx, int cy, int r, uint32_t color) {
    for (int y = -r; y <= r; y++)
        for (int x = -r; x <= r; x++)
            if (x*x + y*y <= r*r)
                put_pixel(cx + x, cy + y, color);
}

